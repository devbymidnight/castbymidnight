import fs from 'node:fs';
import assert from 'node:assert/strict';
const origin='https://castbymidnight.pages.dev';
const routes=[{file:'out/index.html',lang:'en',url:`${origin}/`},{file:'out/el/index.html',lang:'el',url:`${origin}/el/`}];
const sitemap=fs.readFileSync('out/sitemap.xml','utf8');
const robots=fs.readFileSync('out/robots.txt','utf8');
const titles=[];
for(const route of routes){
  const html=fs.readFileSync(route.file,'utf8');
  assert(html.includes(`<html lang="${route.lang}"`),`Wrong document language: ${route.file}`);
  assert.equal([...html.matchAll(/<h1[ >]/g)].length,1,'Exactly one H1');
  const title=html.match(/<title>(.*?)<\/title>/s)?.[1];
  assert(title?.includes('MIDNIGHT'),'Branded title missing');titles.push(title);
  assert(html.includes(`<link rel="canonical" href="${route.url}"`),'Canonical must reference the current language');
  for(const alt of routes)assert(html.includes(`hrefLang="${alt.lang}" href="${alt.url}"`),'Reciprocal language alternate missing');
  assert(html.includes(`hrefLang="x-default" href="${origin}/"`),'English default missing');
  assert(html.includes('<meta name="description" content="'),'Description missing');
  assert(html.includes('<meta property="og:image" content="https://'),'Absolute sharing image missing');
  assert(html.includes('<meta name="twitter:card" content="summary_large_image"'),'Social card missing');
  assert(!html.includes('noindex'),'Public content accidentally blocked');
  const schema=JSON.parse(html.match(/<script type="application\/ld\+json">(.*?)<\/script>/s)?.[1]??'null');
  const profile=schema['@graph'].find(node=>node['@type']==='ProfilePage');
  const service=schema['@graph'].find(node=>node['@type']==='Service');
  assert.equal(profile.url,route.url);
  assert.equal(profile.mainEntity.name,'Alexandros Georgiou');
  assert.equal(profile.inLanguage,route.lang);
  assert(profile.mainEntity.sameAs.includes('https://www.twitch.tv/gu_midnight'),'Twitch profile URL missing from structured data');
  assert(html.includes('href="https://www.twitch.tv/gu_midnight"'),'Correct Twitch profile link missing');
  assert(!html.includes('https://www.twitch.tv/gumidnight'),'Outdated Twitch profile link remains');
  assert.equal(service.provider['@id'],profile.mainEntity['@id']);
  assert.deepEqual(service.areaServed.map(area=>area.name),['Cyprus','Greece']);
  assert(sitemap.includes(`<loc>${route.url}</loc>`),'Missing sitemap page');
  for(const match of html.matchAll(/href="#([^" ]+)"/g))assert(html.includes(`id="${match[1]}"`),`Broken anchor: ${match[1]}`);
}
assert.notEqual(titles[0],titles[1],'Localised titles must be distinct');
assert.equal([...sitemap.matchAll(/<loc>/g)].length,2,'Only two public canonical pages');
assert(robots.includes(`Sitemap: ${origin}/sitemap.xml`));
assert(robots.includes('Allow: /'));
assert(!/localhost|127\.0\.0\.1/.test(sitemap),'Local URL leaked to sitemap');
assert(fs.readFileSync('out/404.html','utf8').includes('noindex'),'404 must not be indexed');
console.log('PASS: both static pages have correct languages, distinct titles, self-canonicals, reciprocal hreflang, sharing tags and valid linked profile/service JSON-LD; sitemap, robots and 404 indexing checks pass.');
